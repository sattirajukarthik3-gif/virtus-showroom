/* Scroll keyframes. p runs 0–100 over the whole page. Each track is [[p, value], ...] with smoothstep between keys. */
import { WX, TR } from '../scene/builders.js';

export function track(keys, step) {
  return p => {
    if (p <= keys[0][0]) return keys[0][1];
    for (let i = 1; i < keys.length; i++) {
      if (p <= keys[i][0]) {
        const t0 = keys[i - 1][0], v0 = keys[i - 1][1], t1 = keys[i][0], v1 = keys[i][1];
        if (step) return v0;
        const u = t1 === t0 ? 1 : (p - t0) / (t1 - t0), e = u * u * (3 - 2 * u);
        return Array.isArray(v0) ? v0.map((a, k) => a + (v1[k] - a) * e) : v0 + (v1 - v0) * e;
      }
    }
    return keys[keys.length - 1][1];
  };
}

